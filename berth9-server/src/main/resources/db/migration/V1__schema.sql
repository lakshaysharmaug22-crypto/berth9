-- ---------------------------------------------------------------- reference data (the buyer's ERP)

CREATE TABLE purchase_order (
    po_number     VARCHAR(40)  PRIMARY KEY,
    supplier_id   VARCHAR(40)  NOT NULL,
    currency      VARCHAR(3)   NOT NULL,
    po_date       DATE         NOT NULL,
    status        VARCHAR(20)  NOT NULL
);

CREATE TABLE po_line (
    po_number     VARCHAR(40)   NOT NULL REFERENCES purchase_order (po_number),
    sku           VARCHAR(60)   NOT NULL,
    description   VARCHAR(200),
    ordered_qty   NUMERIC(18,3) NOT NULL,
    invoiced_qty  NUMERIC(18,3) DEFAULT 0 NOT NULL,
    unit_price    NUMERIC(18,4) NOT NULL,
    uom           VARCHAR(10),
    PRIMARY KEY (po_number, sku)
);

CREATE TABLE product (
    sku           VARCHAR(60)   PRIMARY KEY,
    description   VARCHAR(200),
    uom           VARCHAR(10),
    list_price    NUMERIC(18,4) NOT NULL,
    currency      VARCHAR(3)    NOT NULL
);

CREATE TABLE ship_to (
    customer_id   VARCHAR(40)  NOT NULL,
    ship_to_code  VARCHAR(20)  NOT NULL,
    name          VARCHAR(100),
    city          VARCHAR(60),
    state         VARCHAR(10),
    PRIMARY KEY (customer_id, ship_to_code)
);

CREATE TABLE fx_rate (
    currency      VARCHAR(3)    PRIMARY KEY,
    usd_rate      NUMERIC(18,8) NOT NULL
);
